-- Automatic website quotes (the history behind /api/quote-request) and the customer's first-design brief.
-- Target: the motionvisual-admin Supabase project (ndnapekhhnrbqddfqpdh).
-- Requires the agreements migration (20261015120000) to be applied first: this reuses its
-- agreement_server_key_ok(), so the same AGREEMENTS_SERVER_KEY authorises these RPCs and no new
-- vault secret is needed.
--
-- Team members read quotes and change their status through RLS (column-limited). Customers never
-- touch the table: the website's server functions call the web_quote_* RPCs below with the server key.

create sequence public.web_quote_seq;

create table public.web_quotes (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  issued_on date not null,
  valid_until date not null,
  customer_name text not null,
  customer_email text not null,
  customer_phone text,
  project_type text,
  notes text,
  plan text not null check (plan in ('Essential', 'Signature')),
  extra_pages integer not null check (extra_pages between 0 and 15),
  add_on_ids text[] not null default '{}',
  lines jsonb not null,
  total_pence integer not null check (total_pence > 0),
  deposit_pence integer not null check (deposit_pence > 0),
  balance_pence integer not null check (balance_pence >= 0),
  status text not null default 'issued' check (status in ('issued', 'accepted', 'agreement_sent', 'signed', 'declined', 'lapsed')),
  status_note text,
  customer_email_sent boolean not null default false,
  ip_hash text,
  brief_token text not null unique,
  brief jsonb,
  brief_submitted_at timestamptz
);

comment on table public.web_quotes is 'Quotes generated by POST /api/quote-request (references MV-W-NNNN). The row is the durable history; the quote email attachments are the copy of what the customer received.';

create index web_quotes_created_at_idx on public.web_quotes (created_at desc);
create index web_quotes_ip_hash_idx on public.web_quotes (ip_hash, created_at);
create index web_quotes_email_idx on public.web_quotes (lower(customer_email), created_at);

create or replace function public.web_quotes_touch()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger web_quotes_touch before update on public.web_quotes
  for each row execute function public.web_quotes_touch();

-- ── Team access: read everything, change only the status fields ──────────

alter table public.web_quotes enable row level security;

revoke all on table public.web_quotes from public, anon, authenticated;
grant select on table public.web_quotes to authenticated;
grant update (status, status_note) on table public.web_quotes to authenticated;

create policy team_read on public.web_quotes
  for select using (public.is_team_member());

create policy team_update_status on public.web_quotes
  for update using (public.is_team_member()) with check (public.is_team_member());

-- ── Server-only RPCs (called by the Pages Functions with the server key) ─

create or replace function public.web_quote_create(
  p_key text,
  p_ip_hash text,
  p_name text,
  p_email text,
  p_phone text,
  p_project_type text,
  p_notes text,
  p_plan text,
  p_extra_pages integer,
  p_add_on_ids text[],
  p_lines jsonb,
  p_total_pence integer,
  p_deposit_pence integer,
  p_balance_pence integer,
  p_issued_on date,
  p_valid_until date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v public.web_quotes;
begin
  if not public.agreement_server_key_ok(p_key) then
    raise exception 'not_authorised' using errcode = '42501';
  end if;

  -- Serialise concurrent requests for the same IP / address. Without these locks, N parallel requests would
  -- all count zero existing rows and all insert, defeating the limits below. Always taken in this order.
  perform pg_advisory_xact_lock(hashtext('wq-ip:' || coalesce(p_ip_hash, '')));
  perform pg_advisory_xact_lock(hashtext('wq-email:' || lower(coalesce(p_email, ''))));

  -- Stops the form being used to mail quotes to someone else's address, or to flood us.
  if p_ip_hash is not null and (
    select count(*) from public.web_quotes
    where ip_hash = p_ip_hash and created_at > now() - interval '1 hour'
  ) >= 5 then
    raise exception 'rate_limited';
  end if;
  if (
    select count(*) from public.web_quotes
    where lower(customer_email) = lower(p_email) and created_at > now() - interval '24 hours'
  ) >= 3 then
    raise exception 'rate_limited';
  end if;

  insert into public.web_quotes (
    reference, issued_on, valid_until, customer_name, customer_email, customer_phone, project_type, notes,
    plan, extra_pages, add_on_ids, lines, total_pence, deposit_pence, balance_pence, ip_hash, brief_token
  ) values (
    'MV-W-' || lpad(nextval('public.web_quote_seq')::text, 4, '0'),
    p_issued_on, p_valid_until, left(p_name, 120), left(p_email, 254), left(p_phone, 40), left(p_project_type, 60), left(p_notes, 4000),
    p_plan, p_extra_pages, coalesce(p_add_on_ids, '{}'), p_lines, p_total_pence, p_deposit_pence, p_balance_pence, p_ip_hash,
    left(replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''), 48)
  )
  returning * into v;

  return jsonb_build_object('reference', v.reference, 'briefToken', v.brief_token);
end;
$$;

create or replace function public.web_quote_mark_email(p_key text, p_reference text, p_sent boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.agreement_server_key_ok(p_key) then
    raise exception 'not_authorised' using errcode = '42501';
  end if;
  update public.web_quotes set customer_email_sent = p_sent where reference = p_reference;
end;
$$;

-- What the brief page may show: no email address, no phone.
create or replace function public.web_quote_brief_open(p_key text, p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v public.web_quotes;
begin
  if not public.agreement_server_key_ok(p_key) then
    raise exception 'not_authorised' using errcode = '42501';
  end if;
  select * into v from public.web_quotes where brief_token = p_token;
  if v.id is null then
    return null;
  end if;
  return jsonb_build_object(
    'reference', v.reference,
    'customerName', v.customer_name,
    'plan', v.plan,
    'extraPages', v.extra_pages,
    'addOnIds', to_jsonb(v.add_on_ids),
    'submitted', v.brief_submitted_at is not null
  );
end;
$$;

-- One submission per quote. Returns what the team email needs.
create or replace function public.web_quote_brief_submit(p_key text, p_token text, p_brief jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v public.web_quotes;
begin
  if not public.agreement_server_key_ok(p_key) then
    raise exception 'not_authorised' using errcode = '42501';
  end if;
  select * into v from public.web_quotes where brief_token = p_token for update;
  if v.id is null then
    return null;
  end if;
  if v.brief_submitted_at is not null then
    raise exception 'already_submitted';
  end if;
  update public.web_quotes set brief = p_brief, brief_submitted_at = now() where id = v.id returning * into v;
  return jsonb_build_object(
    'reference', v.reference,
    'customerName', v.customer_name,
    'customerEmail', v.customer_email,
    'plan', v.plan,
    'extraPages', v.extra_pages,
    'addOnIds', to_jsonb(v.add_on_ids),
    'lines', v.lines,
    'totalPence', v.total_pence,
    'status', v.status
  );
end;
$$;

