import { useEffect, useState } from 'react';
import { supabase } from '../../lib/supabase';
import { formatDate, formatGBP } from '../../legal/format';
import { ErrorText, muted, PageTitle, Select } from './ui';

type QuoteRow = {
  id: string;
  reference: string;
  created_at: string;
  valid_until: string;
  customer_name: string;
  customer_email: string;
  customer_phone: string | null;
  project_type: string | null;
  notes: string | null;
  plan: string;
  extra_pages: number;
  add_on_ids: string[];
  lines: { label: string; pounds: number | null; note?: string }[];
  total_pence: number;
  deposit_pence: number;
  status: string;
  status_note: string | null;
  customer_email_sent: boolean;
  brief: Record<string, string> | null;
  brief_submitted_at: string | null;
};

const STATUSES: { value: string; label: string }[] = [
  { value: 'issued', label: 'Issued' },
  { value: 'accepted', label: 'Accepted' },
  { value: 'agreement_sent', label: 'Agreement sent' },
  { value: 'signed', label: 'Signed' },
  { value: 'declined', label: 'Declined' },
  { value: 'lapsed', label: 'Lapsed' },
];

// Quotes generated by the website (/api/quote-request). Team members can read them and change the
// status; everything else is locked by the database (column-level grants + RLS).
export default function QuoteList() {
  const [rows, setRows] = useState<QuoteRow[] | null>(null);
  const [error, setError] = useState('');

  useEffect(() => {
    supabase.from('web_quotes').select('*').order('created_at', { ascending: false })
      .then(({ data, error: err }) => {
        if (err) setError(err.message);
        setRows((data ?? []) as QuoteRow[]);
      });
  }, []);

  const setStatus = async (row: QuoteRow, status: string) => {
    setError('');
    const { error: err } = await supabase.from('web_quotes').update({ status }).eq('id', row.id);
    if (err) { setError(err.message); return; }
    setRows(cur => cur?.map(r => (r.id === row.id ? { ...r, status } : r)) ?? null);
  };

  return (
    <div>
      <PageTitle eyebrow="Studio">Website quotes</PageTitle>
      <p className="font-body font-light text-sm -mt-4 mb-8" style={{ color: 'rgba(237,232,220,0.65)', maxWidth: '62ch' }}>
        Every quote the website has emailed. Keep the status up to date — it is the history. Quotes lapse 14 days after they’re issued.
      </p>

      {error && <ErrorText>{error}</ErrorText>}

      {rows && rows.length === 0 && !error && (
        <p className="font-body font-light text-sm py-10" style={{ color: 'rgba(237,232,220,0.7)' }}>
          No website quotes yet. They appear here as soon as a visitor requests one.
        </p>
      )}

      {rows && rows.length > 0 && (
        <ul className="flex flex-col" style={{ borderBottom: '1px solid rgba(237,232,220,0.07)' }}>
          {rows.map(r => (
            <li key={r.id} style={{ borderTop: '1px solid rgba(237,232,220,0.07)' }}>
              <details className="py-4 group">
                <summary className="grid grid-cols-[1fr_auto] md:grid-cols-[8rem_minmax(0,1fr)_9rem_7rem_11rem] items-center gap-x-6 gap-y-2 cursor-pointer list-none">
                  <span className="font-body text-xs tabular-nums" style={{ color: muted }}>{r.reference}</span>
                  <span className="min-w-0">
                    <span className="block font-body text-sm truncate" style={{ color: '#EDE8DC' }}>{r.customer_name}</span>
                    <span className="block font-body font-light text-xs truncate" style={{ color: muted }}>
                      {r.plan} · {r.customer_email}{r.brief_submitted_at ? ' · brief received' : ''}{r.customer_email_sent ? '' : ' · EMAIL NOT SENT'}
                    </span>
                  </span>
                  <span className="hidden md:block font-body text-xs" style={{ color: muted }}>{formatDate(r.created_at)}</span>
                  <span className="hidden md:block font-body text-sm tabular-nums text-right" style={{ color: '#EDE8DC' }}>{formatGBP(r.total_pence)}</span>
                  <span className="justify-self-end" onClick={e => e.preventDefault()}>
                    <Select aria-label={`Status of ${r.reference}`} value={r.status} onChange={e => setStatus(r, e.target.value)} style={{ padding: '6px 10px', fontSize: '0.8rem' }}>
                      {STATUSES.map(s => <option key={s.value} value={s.value}>{s.label}</option>)}
                    </Select>
                  </span>
                </summary>
                <div className="mt-4 grid gap-4 md:grid-cols-2 font-body text-xs leading-relaxed" style={{ color: 'rgba(237,232,220,0.7)' }}>
                  <div>
                    <p style={{ color: muted }} className="tracking-[0.2em] uppercase text-[9px] mb-1.5">Package</p>
                    <ul>
                      {r.lines.map((l, i) => <li key={i}>{l.label}: {l.pounds === 0 ? 'included' : l.pounds === null ? 'quoted' : formatGBP(l.pounds * 100)}{l.note ? ` (${l.note})` : ''}</li>)}
                    </ul>
                    <p className="mt-2">Total {formatGBP(r.total_pence)} · deposit {formatGBP(r.deposit_pence)} · valid until {formatDate(r.valid_until)}</p>
                    <p className="mt-2">{r.customer_email}{r.customer_phone ? ` · ${r.customer_phone}` : ''}{r.project_type ? ` · ${r.project_type}` : ''}</p>
                    {r.notes && <p className="mt-2 whitespace-pre-wrap">{r.notes}</p>}
                  </div>
                  <div>
                    <p style={{ color: muted }} className="tracking-[0.2em] uppercase text-[9px] mb-1.5">Brief</p>
                    {r.brief
                      ? <dl>{Object.entries(r.brief).filter(([, v]) => v).map(([k, v]) => <div key={k} className="mb-1.5"><dt style={{ color: muted }}>{k}</dt><dd className="whitespace-pre-wrap">{v}</dd></div>)}</dl>
                      : <p>Not submitted yet.</p>}
                  </div>
                </div>
              </details>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
