#!/usr/bin/env node
// Writes docs/commercial-terms.json and docs/commercial-terms.sql from src/commercial.ts.
//
//   npm run sync-terms
//
// Then: copy the JSON into the admin repo (src/generated/commercialTerms.json) and run the SQL in the Supabase
// SQL editor so the admin shows the new terms live. tests/commercial.test.ts fails if the committed files are stale.
import { writeFileSync } from 'node:fs';
import { buildCommercialTerms } from '../src/commercial.ts';
import { POLICY_UPDATED, POLICY_VERSION } from '../src/legal/policy.ts';

const terms = buildCommercialTerms({ version: POLICY_VERSION, updated: POLICY_UPDATED });
const json = JSON.stringify(terms, null, 2) + '\n';
writeFileSync(new URL('../docs/commercial-terms.json', import.meta.url), json);

const literal = JSON.stringify(terms).replace(/'/g, "''");
const sql = `-- Generated by npm run sync-terms. Safe to run more than once.\ninsert into public.commercial_terms (version, terms)\nvalues ('${terms.version}', '${literal}'::jsonb)\non conflict (version) do update set terms = excluded.terms, published_at = now();\n`;
writeFileSync(new URL('../docs/commercial-terms.sql', import.meta.url), sql);
console.log(`Wrote docs/commercial-terms.json and docs/commercial-terms.sql (version ${terms.version})`);
